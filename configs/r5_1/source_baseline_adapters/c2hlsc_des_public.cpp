#include <cstdio>

typedef unsigned char des_key_t[16][6];
typedef unsigned char des_block_t[8];

extern void des_crypt(des_block_t *in, des_block_t *out, des_key_t *key);

int main() {
    des_block_t input = {0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xe7};
    des_key_t schedule = {
        {0x0b,0x02,0x67,0x9b,0x49,0xa5}, {0x69,0xa6,0x59,0x25,0x6a,0x26},
        {0x45,0xd4,0x8a,0xb4,0x28,0xd2}, {0x72,0x89,0xd2,0xa5,0x82,0x57},
        {0x3c,0xe8,0x03,0x17,0xa6,0xc2}, {0x23,0x25,0x1e,0x3c,0x85,0x45},
        {0x6c,0x04,0x95,0x0a,0xe4,0xc6}, {0x57,0x88,0x38,0x6c,0xe5,0x81},
        {0xc0,0xc9,0xe9,0x26,0xb8,0x39}, {0x91,0xe3,0x07,0x63,0x1d,0x72},
        {0x21,0x1f,0x83,0x0d,0x89,0x3a}, {0x71,0x30,0xe5,0x45,0x5c,0x54},
        {0x91,0xc4,0xd0,0x49,0x80,0xfc}, {0x54,0x43,0xb6,0x81,0xdc,0x8d},
        {0xb6,0x91,0x05,0x0a,0x16,0xb5}, {0xca,0x3d,0x03,0xb8,0x70,0x32}
    };
    des_block_t output = {};
    des_crypt(&input, &output, &schedule);
    const unsigned char expected[8] = {0xc9, 0x57, 0x44, 0x25, 0x6a, 0x5e, 0xd3, 0x1d};
    for (int i = 0; i < 8; ++i) {
        if (output[i] != expected[i]) {
            std::fprintf(
                stderr,
                "C2HLSC_DES_MISMATCH index=%d actual=%02x expected=%02x\n",
                i,
                output[i],
                expected[i]
            );
            return 1;
        }
    }
    std::puts("C2HLSC_DES_SOURCE_ORACLE=passed");
    return 0;
}
